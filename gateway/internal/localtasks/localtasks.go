// Package localtasks detects heavy tasks running on the gateway host so the
// operator can pick one and dispatch a copy to a remote worker.
//
// The scanner probes three well-known ports (ComfyUI :8188, SD WebUI :7860,
// Ollama :11434) and enumerates processes matching known heavy names
// (ffmpeg.exe, blender.exe) plus any user-defined patterns from
// localtasks.yaml. Each detected entity is mapped (MapLocalTask) to a gateway
// task type + payload template; the operator picks a card in the web UI and
// clicks "扔到远端" to dispatch a copy via the existing dispatchTaskWithParams
// path. The LOCAL task is never stopped — the dispatch is parallel and
// independent.
//
// Nothing in this package touches workers directly. All dispatching goes
// through the gateway's HTTP API.
package localtasks

import "time"

// Known heavy services we probe for. Values are stable strings — they appear
// in JSON responses, the UI, and the YAML config schema.
const (
	SvcComfyUI = "comfyui"
	SvcSDWebUI = "sdwebui"
	SvcOllama  = "ollama"
	SvcFFmpeg  = "ffmpeg"
	SvcBlender = "blender"
)

// Status reflects whether the detected local task is actively doing work.
//
//	busy    — probe saw an in-flight job (e.g. ComfyUI queue_remaining > 0,
//	          SD progress > 0, FFmpeg process not yet exited)
//	idle    — service is up but no work in progress (e.g. ComfyUI idle queue)
//	unknown — could not determine (process probe only, no port to query)
const (
	StatusBusy    = "busy"
	StatusIdle    = "idle"
	StatusUnknown = "unknown"
)

// SourceHint tells the UI how a LocalTask was discovered.
const (
	SourcePort    = "port"
	SourceProcess = "process"
	SourceYAML    = "yaml"
)

// LocalTask is one detected heavy task on the gateway host.
//
// ID is generated by the registry on first sighting; it persists across scans
// as long as the underlying entity (svc + port + pid) keeps matching. Once
// the entity disappears for > disappearanceTTL, the ID is dropped.
type LocalTask struct {
	ID         string            `json:"id"`
	Service    string            `json:"service"`            // comfyui | sdwebui | ollama | ffmpeg | blender | <yaml-name>
	Title      string            `json:"title"`              // human-readable, e.g. "ComfyUI @ :8188"
	Port       int               `json:"port,omitempty"`     // listening port (0 if not applicable)
	PID        int32             `json:"pid,omitempty"`      // OS process id (0 if not applicable)
	Status     string            `json:"status"`             // busy | idle | unknown
	DetectedAt time.Time         `json:"detected_at"`
	LastSeen   time.Time         `json:"last_seen"`
	MapToType  string            `json:"map_to_type"`        // suggested gateway task type (empty if !ok)
	PayloadTpl string            `json:"payload_tpl"`        // suggested payload body
	Metadata   map[string]any    `json:"metadata,omitempty"` // raw probe result (queue size, model name, etc.)
	SourceHint string            `json:"source_hint"`        // port | process | yaml
}

// CustomRule is one entry from localtasks.yaml. Either NamePattern (process
// match) or Port (port probe) must be set. Type + PayloadTemplate are copied
// verbatim into the LocalTask, with {{pid}} / {{name}} / {{cmdline}} /
// {{port}} substituted at scan time.
type CustomRule struct {
	Name            string `yaml:"name"               json:"name"`
	NamePattern     string `yaml:"name_pattern,omitempty" json:"name_pattern,omitempty"`
	Port            int    `yaml:"port,omitempty"     json:"port,omitempty"`
	Type            string `yaml:"type"               json:"type"`
	PayloadTemplate string `yaml:"payload_template"   json:"payload_template"`
}

// YAMLConfig is the top-level shape of localtasks.yaml.
type YAMLConfig struct {
	Rules []CustomRule `yaml:"rules" json:"rules"`
}

// Probe ports (TCP localhost). These are the well-known defaults for the
// heavy services we auto-detect. Users with non-default ports add a `port:`
// rule in localtasks.yaml.
const (
	defaultComfyUIPort = 8188
	defaultSDWebUIPort = 7860
	defaultOllamaPort  = 11434
)

// probeTimeout is the per-probe HTTP/TCP budget. Kept short so a host with
// nothing running completes the whole scan in well under 200ms.
const probeTimeout = 800 * time.Millisecond

// disappearanceTTL is how long after the last sighting we keep an entry in
// the snapshot. After this elapses without a fresh match, the entry is
// dropped. Set generously enough that a transient probe failure (e.g. slow
// ComfyUI) doesn't yank a card from the UI.
const disappearanceTTL = 30 * time.Second

// scanIntervalDefault is the default background scan period. Override via
// GATEWAY_LOCALTASKS_INTERVAL env var.
const scanIntervalDefault = 10 * time.Second
